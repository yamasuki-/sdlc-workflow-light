"""プロジェクト側の準備（`scripts/sdlc init`）: ランチャ・CLAUDE.md の import・.gitignore。

本体は ~/.claude/sdlc（全プロジェクト共通）またはプロジェクトの .claude/sdlc に置く。
プロジェクトには本体へのランチャ scripts/sdlc・scripts/approve だけを置き、どちらの配置でも同じコマンドで使えるようにする。
"""
from __future__ import annotations

import os
import re
from pathlib import Path

from .config import install_mode

LAUNCHER = r'''#!/usr/bin/env bash
# SDLC ワークフローのランチャ（scripts/sdlc init が生成。編集しない）。
# 本体はプロジェクトの .claude/sdlc/bin を優先し、無ければ ~/.claude/sdlc/bin を使う。
# Windows の PowerShell / コマンドプロンプトでは同じ名前の .cmd を使う。
src="${BASH_SOURCE[0]//\\//}"          # Windows のパス（C:\...）でも動くよう区切りを / にそろえる
root="$(cd "${src%/*}/.." && pwd)"
name="${src##*/}"
for base in "$root/.claude" "$HOME/.claude" "${USERPROFILE:+$USERPROFILE/.claude}"; do
  [ -n "$base" ] || continue
  if [ -f "$base/sdlc/bin/$name" ]; then
    exec bash "$base/sdlc/bin/py" "$base/sdlc/bin/$name" "$@"
  fi
done
echo "SDLC ワークフロー本体（.claude/sdlc/bin/${name}）が見つかりません。USAGE.md のインストール手順を参照してください。" >&2
exit 1
'''

# cmd.exe はバッチファイルをコンソールのコードページ（日本語環境では cp932）で読むため、ASCII だけで書く
LAUNCHER_CMD = r'''@echo off
rem SDLC workflow launcher (generated by "scripts/sdlc init"; do not edit). For PowerShell / Command Prompt.
rem Uses the project's .claude\sdlc\bin first, then %USERPROFILE%\.claude\sdlc\bin.
setlocal
set "PYTHONUTF8=1"
set "NAME=%~n0"
set "BIN=%~dp0..\.claude\sdlc\bin\%NAME%"
if not exist "%BIN%" set "BIN=%USERPROFILE%\.claude\sdlc\bin\%NAME%"
if not exist "%BIN%" goto notfound
if defined SDLC_PYTHON goto custom
where py >nul 2>nul
if errorlevel 1 goto plain
py -3 "%BIN%" %*
exit /b
:plain
python "%BIN%" %*
exit /b
:custom
%SDLC_PYTHON% "%BIN%" %*
exit /b
:notfound
echo SDLC workflow body (.claude\sdlc\bin\%NAME%) was not found. See USAGE.md for installation. 1>&2
exit /b 1
'''

IMPORT_MARK = "<!-- sdlc-workflow-light: 全体ルール（scripts/sdlc init が管理） -->"
IMPORT_RE = re.compile(r"^@\S*\.claude/sdlc/RULES\.md\s*$", re.MULTILINE)
GITIGNORE_LINES = [".sdlc/", ".claude/settings.local.json"]
# Windows の git（core.autocrlf）で bash スクリプトの改行が CRLF にならないようにする
GITATTRIBUTES_LINES = ["scripts/sdlc text eol=lf", "scripts/approve text eol=lf",
                       "scripts/*.cmd text eol=crlf", ".claude/sdlc/bin/* text eol=lf",
                       ".claude/hooks/sdlc/run text eol=lf"]


def write_launchers(root) -> list[str]:
    out = []
    for name in ("sdlc", "approve"):
        for fname, text, newline in ((name, LAUNCHER, "\n"), (f"{name}.cmd", LAUNCHER_CMD, "\r\n")):
            p = Path(root) / "scripts" / fname
            data = text.replace("\n", newline).encode("utf-8")
            if p.exists() and p.read_bytes() == data:
                continue
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_bytes(data)
            os.chmod(p, 0o755)
            out.append(p.relative_to(root).as_posix())
    return out


def rules_import_line(root) -> str:
    return "@.claude/sdlc/RULES.md" if install_mode(root) == "project" else "@~/.claude/sdlc/RULES.md"


def ensure_claude_md(root) -> str | None:
    """プロジェクトの CLAUDE.md に全体ルールの import を入れる（配置に合わせて書き換える）。"""
    p = Path(root) / "CLAUDE.md"
    line = rules_import_line(root)
    text = p.read_text(encoding="utf-8") if p.exists() else ""
    if IMPORT_RE.search(text):
        new = IMPORT_RE.sub(line, text, count=1)
    else:
        new = text.rstrip("\n") + ("\n\n" if text.strip() else "") + f"{IMPORT_MARK}\n{line}\n"
    if new == text:
        return None
    p.write_text(new, encoding="utf-8")
    return line


def _ensure_lines(path: Path, lines: list[str]) -> list[str]:
    text = path.read_text(encoding="utf-8") if path.exists() else ""
    have = {ln.strip() for ln in text.splitlines()}
    add = [ln for ln in lines if ln not in have]
    if add:
        path.write_text(text.rstrip("\n") + ("\n" if text.strip() else "") + "\n".join(add) + "\n", encoding="utf-8")
    return add


def ensure_gitignore(root) -> list[str]:
    return _ensure_lines(Path(root) / ".gitignore", GITIGNORE_LINES)


def ensure_gitattributes(root) -> list[str]:
    return _ensure_lines(Path(root) / ".gitattributes", GITATTRIBUTES_LINES)
